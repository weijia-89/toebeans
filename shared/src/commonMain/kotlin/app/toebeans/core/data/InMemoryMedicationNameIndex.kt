package app.toebeans.core.data

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.IO
import kotlinx.coroutines.withContext
import kotlinx.serialization.Serializable

/**
 * In-memory implementation of [MedicationNameIndexRepository].
 *
 * Medication names are bundled as a Kotlin constant for simplicity.
 * Searches are performed in-memory with case-insensitive matching.
 *
 * Search algorithm:
 * - Exact match (case-insensitive) ranks first
 * - Prefix match (query at start of name) ranks second
 * - Substring match (query anywhere in name) ranks third
 * - Results within each tier are sorted alphabetically
 */
public class InMemoryMedicationNameIndex(
    private val medicationList: List<String> = BUNDLED_MEDICATION_NAMES,
) : MedicationNameIndexRepository {
    private var medicationNames: List<String>? = null
    private val loadLock = Any()

    private suspend fun ensureLoaded() {
        if (medicationNames != null) return
        withContext(Dispatchers.IO) {
            synchronized(loadLock) {
                if (medicationNames == null) {
                    medicationNames = medicationList.sortedBy { it.lowercase() }
                }
            }
        }
    }

    override suspend fun search(
        query: String,
        limit: Int,
    ): List<String> {
        if (query.isBlank()) return getAll().take(limit)
        ensureLoaded()
        val names = medicationNames ?: return emptyList()
        val normalizedQuery = query.trim().lowercase()
        if (normalizedQuery.isEmpty()) return emptyList()
        val exact = mutableListOf<String>()
        val prefix = mutableListOf<String>()
        val substring = mutableListOf<String>()
        for (name in names) {
            val lower = name.lowercase()
            when {
                lower == normalizedQuery -> exact += name
                lower.startsWith(normalizedQuery) -> prefix += name
                lower.contains(normalizedQuery) -> substring += name
            }
        }
        val results =
            exact.sortedBy { it.lowercase() } +
                prefix.sortedBy { it.lowercase() } +
                substring.sortedBy { it.lowercase() }
        return results.take(limit)
    }

    override suspend fun getAll(): List<String> {
        ensureLoaded()
        return medicationNames ?: emptyList()
    }
}

